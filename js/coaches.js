/** Legacy saved settings stored team names. Migrate them to coach names. */
export const TEAM_TO_COACH = Object.fromEntries(
  COACHES.flatMap((c) => [[c.team2025, c.name], [c.yahoo, c.name]]),
);

export const coachByName = (name) => COACHES.find((c) => c.name === name) || null;

/**
 * The positions this coach reliably takes early enough to be worth planning
 * around. Anything with a spread wider than RELIABLE_SPREAD is dropped -- an
 * average of "round 4" built from rounds 1 and 7 predicts nothing.
 */
export function reliableHabits(coach) {
  if (!coach) return [];
  return Object.entries(coach.first)
    .filter(([, [, , verdict]]) => USABLE_VERDICTS.has(verdict))
    .map(([pos, [mean, spread, verdict, priorMean]]) => ({
      pos, round: mean, spread, verdict, priorMean,
    }))
    .sort((a, b) => a.round - b.round);
}

/**
 * One-line human summary, e.g. "RB r1.0 (10yr), TE r3.8 (moved up from 5.7)".
 * The parenthetical is the confidence: a decade-long trait reads differently
 * from one that changed recently, and both differ from a bare average.
 */
export function habitSummary(coach) {
  const habits = reliableHabits(coach).filter((h) => h.pos !== 'K' && h.pos !== 'DST');
  if (!habits.length) return 'no reliable pattern';
  return habits.map((h) => {
    const r = `${h.pos} r${h.round.toFixed(1)}`;
    if (h.verdict === 'drifted' && h.priorMean != null) {
      const dir = h.round < h.priorMean ? 'moved up from' : 'moved back from';
      return `${r} (${dir} ${h.priorMean.toFixed(1)})`;
    }
    if (h.verdict === 'confirmed') return `${r} (10yr${h.spread === 0 ? ', never varies' : ''})`;
    return r;
  }).join(', ');
}

/**
 * Which coaches pick between now and your next turn, in order.
 * Pure: takes the snake math as an argument so it stays testable headlessly.
 */
export function coachesUntilMyTurn(draftOrder, slotOnClock, currentPickNo, myNextPickNo) {
  const out = [];
  for (let p = currentPickNo; p < myNextPickNo; p += 1) {
    const slot = slotOnClock(p);
    const name = draftOrder[slot - 1];
    if (name) out.push({ pickNo: p, slot, name, coach: coachByName(name) });
  }
  return out;
}

/**
 * Positions at elevated risk of being gone before your next pick, based on who
 * is actually on the clock between now and then.
 *
 * This adjusts *timing*, never value: it can tell you a tier will not survive,
 * it must not tell you a worse player is better. Returns positions with the
 * count of upcoming coaches whose reliable habit lands on or before this round.
 */
export function positionsAtRisk(upcoming, round) {
  const tally = {};
  for (const { coach } of upcoming) {
    for (const h of reliableHabits(coach)) {
      // A habit predicts a pick only once the coach has reached that round.
      if (round >= h.round - 1) tally[h.pos] = (tally[h.pos] || 0) + 1;
    }
  }
  return Object.entries(tally)
    .map(([pos, count]) => ({ pos, count }))
    .sort((a, b) => b.count - a.count);
}
