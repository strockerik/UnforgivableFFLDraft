//
// Every pick in that history was made live and in person. There is no
// autodraft in this league, so a repeated pattern is a real habit and a noisy
// one is a genuinely unpredictable drafter, not a data artifact.
//
// Each entry is [recentMean, recentSpread, verdict, priorMean]:
//   recentMean    mean round of their first pick at that position, 2022-2025
//   recentSpread  range across those seasons; 0 means identical every year
//   verdict       how 2016-21 relates to it:
//                   confirmed   - the same behaviour for a decade
//                   steady-mean - same average, but they used to be erratic
//                   drifted     - they changed; the recent number is the real one
//                   noisy       - no usable pattern even recently
//   priorMean     the 2016-21 mean, kept so drift is visible rather than hidden
//
// Only the recent era establishes a habit. Averaging ten years would blend two
// different drafters -- Josh took his first QB in round 6 for six seasons and
// round 4.5 for the last four, and the decade average describes neither.
//
// Generated by tools/analyze_draft_tendencies.py; regenerate after a season.

